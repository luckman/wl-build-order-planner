import { expect, test } from "@playwright/test"

for (const faction of ["Light", "Dark"]) test(`${faction} mana well dropdown, ownership validation and timestamp-only dialogs work on desktop and mobile`, async ({ page }) => {
    for (const width of [1280, 390]) {
        await page.setViewportSize({ width, height: 900 })
        await page.goto("http://localhost:2987")
        await page.evaluate(() => localStorage.clear())
        await page.reload()
        await page.getByRole("button", { name: faction, exact: true }).click()
        const heroes = page.getByRole("region", { name: "heroes", exact: true })
        const point = heroes.getByRole("button", { name: "Point is Captured / Lost", exact: true })
        const menu = page.getByRole("menu", { name: "Point is Captured / Lost" })
        const capture = menu.getByRole("menuitem", { name: "Mana well is captured", exact: true })
        const lose = menu.getByRole("menuitem", { name: "Mana well is lost", exact: true })
        await point.scrollIntoViewIfNeeded()
        await point.click()
        await lose.click()
        let dialog = page.getByRole("dialog", { name: "Mana well is lost" })
        await expect(dialog.getByRole("textbox")).toHaveCount(1)
        await expect(dialog.getByRole("textbox")).toBeFocused()
        await expect(dialog.getByRole("alert")).toContainText("at least one owned mana well")
        await expect(dialog.getByRole("button", { name: "Add event" })).toBeDisabled()
        const bounds = (await dialog.boundingBox())!
        expect(bounds.x).toBeGreaterThanOrEqual(0)
        expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
        await dialog.screenshot({ path: `test-results/mana-well-is-lost-dialog-${faction}-${width}.png` })
        await dialog.getByRole("button", { name: "Cancel" }).click()
        await expect(point).toBeFocused()
        await point.click()
        await capture.click()
        dialog = page.getByRole("dialog", { name: "Mana well is captured" })
        await expect(dialog.getByRole("textbox")).toHaveCount(1)
        await expect(dialog.getByRole("textbox")).toBeFocused()
        await expect(dialog.getByRole("textbox")).toHaveValue("00:01")
        await dialog.getByRole("textbox").fill("0000")
        await dialog.getByRole("button", { name: "Add event" }).click()
        await expect(page.getByRole("button", { name: "Remove Mana well is captured", exact: true })).toBeVisible()
        await expect(page.locator(".resource-summary")).not.toContainText("Mana wells")
        await expect(point).toBeFocused()
        await point.click()
        await lose.click()
        dialog = page.getByRole("dialog", { name: "Mana well is lost" })
        await dialog.getByRole("textbox").fill("0010")
        await dialog.getByRole("button", { name: "Add event" }).click()
        await expect(page.getByRole("button", { name: "Remove Mana well is lost", exact: true })).toBeVisible()
        await expect(page.locator(".order-blocked")).toHaveCount(0)
        await expect(page.locator(".resource-summary")).toContainText("Mana 46 / 50")
        await page.reload()
        await expect(page.getByRole("button", { name: "Remove Mana well is captured", exact: true })).toBeVisible()
        await page.getByRole("button", { name: "Remove Mana well is captured", exact: true }).click()
        await expect(page.locator(".order-blocked")).toContainText("Mana well is lost requires at least one")
        await page.getByRole("button", { name: faction === "Light" ? "Dark" : "Light", exact: true }).click()
        await point.click()
        await expect(capture).toBeVisible()
        await expect(lose).toBeVisible()
    }
})

test("the point menu dismisses without changing the build order", async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 900 })
    await page.goto("http://localhost:2987")
    const heroes = page.getByRole("region", { name: "heroes", exact: true })
    const point = heroes.getByRole("button", { name: "Point is Captured / Lost" })
    const menu = page.getByRole("menu", { name: "Point is Captured / Lost" })
    const unitKilled = heroes.getByRole("button", { name: "Unit is killed" })

    await point.scrollIntoViewIfNeeded()
    await point.press("Space")
    await expect(menu.getByRole("menuitem").first()).toBeFocused()
    await page.keyboard.press("Tab")
    await expect(menu).toHaveCount(0)
    await expect(unitKilled).toBeFocused()

    await point.click()
    await point.click()
    await expect(menu).toHaveCount(0)
    await point.press("ArrowDown")
    await expect(menu.getByRole("menuitem").first()).toBeFocused()
    await page.mouse.click(1, 1)
    await expect(menu).toHaveCount(0)

    await point.click()
    await page.setViewportSize({ width: 395, height: 900 })
    await expect(menu).toHaveCount(0)
    await point.click()
    await heroes.locator(".hero-scroll-grid").evaluate(grid => { grid.scrollLeft = 0 })
    await expect(menu).toHaveCount(0)
    await expect(page.getByRole("button", { name: /^Remove Mana well/ })).toHaveCount(0)
    await expect(page.getByRole("dialog")).toHaveCount(0)
})
