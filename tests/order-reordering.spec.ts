import { expect, test } from "@playwright/test"

test("mouse reordering recalculates dependency warnings, and keyboard reordering restores the plan", async ({ page }) => {
    await page.goto("http://localhost:2987")
    await page.getByLabel("Starting gold", { exact: true }).fill("2000")
    await page.getByLabel("Starting wood", { exact: true }).fill("2000")
    await page.locator(".action-panel").getByRole("button", { name: /^Barracks \d/ }).click()
    await page.locator(".action-panel").getByRole("button", { name: /^Swordsman \d/ }).click()
    const rows = page.locator(".sortable-order > li")
    await expect(rows).toHaveCount(2)
    const originalTimings = await rows.evaluateAll(elements => elements.map(element => element.getAttribute("title")))
    const handle = page.getByRole("button", { name: "Reorder Swordsman, action 2" })
    const box = (await handle.boundingBox())!
    const first = (await rows.first().boundingBox())!
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 - 10, { steps: 5 })
    await expect(page.locator(".order-dragging")).toHaveCount(1)
    await page.mouse.move(box.x + box.width / 2, first.y + first.height / 2 - 5, { steps: 15 })
    await expect(page.locator('[aria-live="assertive"]')).toContainText("position 1")
    await page.mouse.up()
    await expect(rows.first()).toContainText("Swordsman")
    await expect(rows.first()).toHaveClass(/order-blocked/)
    await expect(rows.nth(1)).not.toHaveClass(/order-blocked/)
    await expect(page.getByRole("region", { name: "Blocked actions" })).toContainText("Requires")
    await expect(page.locator(".event.unit")).toHaveCount(0)

    const restore = page.getByRole("button", { name: "Reorder Swordsman, action 1" })
    await restore.focus()
    await restore.press("Space")
    await expect(page.locator(".order-dragging")).toHaveCount(1)
    await restore.press("ArrowDown")
    await expect(page.locator('[aria-live="assertive"]')).toContainText("position 2")
    await restore.press("Space")
    await expect(rows.first()).toContainText("Barracks")
    await expect(page.getByRole("region", { name: "Blocked actions" })).toHaveCount(0)
    await expect.poll(() => rows.evaluateAll(elements => elements.map(element => element.getAttribute("title")))).toEqual(originalTimings)
})

test("repeated actions keep their identity and cancelled drags preserve order", async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 900 })
    await page.goto("http://localhost:2987")
    await page.locator(".action-panel").getByRole("button", { name: /^Worker \d/ }).click()
    await page.locator(".action-panel").getByRole("button", { name: /^Worker \d/ }).click()
    const rows = page.locator(".sortable-order > li")
    const ids = await rows.evaluateAll(elements => elements.map(element => element.getAttribute("data-rfd-draggable-id")))
    const handle = page.getByRole("button", { name: "Reorder Worker, action 2" })
    await handle.focus()
    await handle.press("Space")
    await expect(page.locator(".order-dragging")).toHaveCount(1)
    await handle.press("ArrowUp")
    await expect(page.locator('[aria-live="assertive"]')).toContainText("position 1")
    await handle.press("Escape")
    await expect(page.locator(".order-dragging")).toHaveCount(0)
    await expect.poll(() => rows.evaluateAll(elements => elements.map(element => element.getAttribute("data-rfd-draggable-id")))).toEqual(ids)
    await handle.press("Space")
    await expect(page.locator(".order-dragging")).toHaveCount(1)
    await handle.press("ArrowUp")
    await expect(page.locator('[aria-live="assertive"]')).toContainText("position 1")
    await handle.press("Space")
    await expect.poll(() => rows.evaluateAll(elements => elements.map(element => element.getAttribute("data-rfd-draggable-id")))).toEqual([...ids].reverse())
    await page.getByRole("button", { name: "Remove Worker" }).first().click()
    await expect(rows).toHaveCount(1)
    await expect(rows.first()).toHaveAttribute("data-rfd-draggable-id", ids[0]!)
})
