const { test } = require('node:test')
const assert = require('node:assert/strict')
const { spawnSync } = require('node:child_process')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const runner = path.join(__dirname, 'run.cjs')
const results = path.join(root, 'benchmark-results')
const files = () => fs.existsSync(results) ? fs.readdirSync(results).filter(name => name.endsWith('.json')) : []
test('rejects unknown benchmark arguments without saving a result', () => {
    const before = files()
    const result = spawnSync(process.execPath, [runner, '--unknown'], { encoding: 'utf8' })
    assert.notEqual(result.status, 0)
    assert.match(result.stderr, /unknown/i)
    assert.deepEqual(files(), before)
})
test('saves the Dark measurements even when Git is unavailable', { timeout: 180000 }, () => {
    const before = new Set(files())
    const result = spawnSync(process.execPath, [runner, '--suite=dark', '--smoke'], { cwd: root, env: { ...process.env, PATH: '' }, encoding: 'utf8', timeout: 170000 })
    assert.equal(result.status, 0, result.stderr)
    const added = files().filter(name => !before.has(name))
    assert.equal(added.length, 1)
    const saved = JSON.parse(fs.readFileSync(path.join(results, added[0]), 'utf8'))
    assert.equal(saved.formatVersion, 1)
    assert.equal(saved.revision, null)
    assert.equal(saved.workingTree, null)
    assert.equal(saved.suites[0].scenarios.length, 2)
    assert.equal(saved.suites[0].scenarios[0].samples.length, 1)
    assert.equal(saved.suites[0].fixtureHashes.length, 2)
})
test('rejects conflicting modes and case filters without the middle suite', () => {
    for (const [args, message] of [[['--quick', '--smoke'], /conflict/i], [['--suite=dark', '--case=Insert'], /middle/i], [['--suite=middle', '--case=No such case'], /no matching/i]]) {
        const before = files()
        const result = spawnSync(process.execPath, [runner, ...args], { cwd: root, encoding: 'utf8' })
        assert.notEqual(result.status, 0, args.join(' '))
        assert.match(result.stderr, message)
        assert.deepEqual(files(), before)
    }
})
test('runs selected edit suites and preserves actual modes and samples', { timeout: 180000 }, () => {
    const before = new Set(files())
    const result = spawnSync(process.execPath, [runner, '--suite=last', '--suite=middle', '--quick', '--case=Insert'], { cwd: root, encoding: 'utf8', timeout: 170000 })
    assert.equal(result.status, 0, result.stderr)
    const added = files().filter(name => !before.has(name))
    assert.equal(added.length, 1)
    const saved = JSON.parse(fs.readFileSync(path.join(results, added[0]), 'utf8'))
    assert.deepEqual(saved.suites.map(s => [s.name, s.mode, s.warmups, s.rounds, s.scenarios.length]), [['last', 'full', 5, 21, 4], ['middle', 'quick', 2, 7, 1]])
    assert(saved.suites.every(s => s.scenarios.every(c => c.samples.length === s.rounds)))
})
test('smoke mode exercises every suite once', { timeout: 180000 }, () => {
    const before = new Set(files())
    const result = spawnSync(process.execPath, [runner, '--smoke'], { cwd: root, encoding: 'utf8', timeout: 170000 })
    assert.equal(result.status, 0, result.stderr)
    const added = files().filter(name => !before.has(name))
    assert.equal(added.length, 1)
    const saved = JSON.parse(fs.readFileSync(path.join(results, added[0]), 'utf8'))
    assert.deepEqual(saved.suites.map(s => [s.name, s.mode, s.warmups, s.rounds, s.scenarios.length]), [['dark', 'smoke', 0, 1, 2], ['last', 'smoke', 0, 1, 4], ['middle', 'smoke', 0, 1, 5]])
    assert(saved.suites.every(s => s.scenarios.every(c => c.samples.length === 1)))
})
