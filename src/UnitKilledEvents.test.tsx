import { fireEvent, render, screen, within } from "@testing-library/react"
import App from "./App"

beforeEach(() => window.localStorage.clear())
afterEach(() => window.localStorage.clear())

test("Unit is killed selects a timestamp and unit type, validates existence, releases food and persists", () => {
    const view = render(<App />)
    fireEvent.click(screen.getByRole("button", { name: "Unit is killed", exact: true }))
    let dialog = within(screen.getByRole("dialog", { name: "Unit is killed" }))
    expect((dialog.getByLabelText("Command time (mm:ss)") as HTMLInputElement).value).toBe("00:01")
    expect(dialog.getByRole("option", { name: "Worker", exact: true })).toBeTruthy()
    expect(dialog.getByRole("option", { name: "Swordsman", exact: true })).toBeTruthy()
    expect(dialog.getByRole("option", { name: "Gilbert", exact: true })).toBeTruthy()
    fireEvent.change(dialog.getByLabelText("Unit type"), { target: { value: "swordsman" } })
    expect(dialog.getByRole("alert").textContent).toContain("living Swordsman")
    expect((dialog.getByRole("button", { name: "Add event" }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(dialog.getByLabelText("Unit type"), { target: { value: "worker" } })
    fireEvent.change(dialog.getByLabelText("Command time (mm:ss)"), { target: { value: "0000" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add event" }))
    expect(view.container.querySelector(".resource-summary")?.textContent).toContain("Food 8 / 20")
    expect(view.container.querySelector(".resource-summary")?.textContent).toContain("Total workers 4")
    expect(view.container.querySelector(".resource-summary")?.textContent).toContain("Gathering wood 0")
    expect(view.container.querySelector(".order li")?.textContent).toContain("Worker")
    fireEvent.click(screen.getByRole("button", { name: "Change Unit is killed timestamp, action 1" }))
    dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Command time (mm:ss)"), { target: { value: "0020.5" } })
    expect((dialog.getByLabelText("Command time (mm:ss)") as HTMLInputElement).value).toBe("00:20")
    fireEvent.click(dialog.getByRole("button", { name: "Save event" }))
    expect(JSON.parse(window.localStorage.getItem("wl-build-draft-v2-light")!).buildOrder[1]).toEqual({ type: "unit-is-killed", unitId: "worker", commandTime: 20 })
    view.unmount()
    render(<App />)
    expect(screen.getByRole("button", { name: "Remove Unit is killed" })).toBeTruthy()
    fireEvent.click(screen.getByRole("button", { name: "Dark", exact: true }))
    const card = screen.getByRole("button", { name: "Unit is killed", exact: true })
    expect(card.querySelector("img")?.getAttribute("src")).toContain("dark-unit-is-killed")
    fireEvent.click(card)
    dialog = within(screen.getByRole("dialog"))
    expect(dialog.getByRole("option", { name: "Slave", exact: true })).toBeTruthy()
    expect(dialog.getByRole("option", { name: "Goon", exact: true })).toBeTruthy()
    expect(dialog.queryByRole("option", { name: "Swordsman", exact: true })).toBeNull()
    fireEvent.click(dialog.getByRole("button", { name: "Add event" }))
    expect(screen.getByRole("button", { name: "Remove Unit is killed" })).toBeTruthy()
})
