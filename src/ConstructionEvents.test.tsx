test.each(["Light", "Dark"])("%s construction pre-add, row and timeline share settings without mutating other occurrences", faction => {
    const view = render(<App />)
    fireEvent.click(screen.getByRole("button", { name: faction, exact: true }))
    const card = screen.getByRole("button", { name: /^Barracks \d/ })
    fireEvent.contextMenu(card)
    let dialog = within(screen.getByRole("dialog", { name: "Configure Barracks Construction" }))
    expect(dialog.getAllByRole("spinbutton").map(input => input.getAttribute("step"))).toEqual(["0.1", "0.1", "0.1"])
    expect(dialog.getAllByText("Global: 3.0 s")).toHaveLength(2)
    expect(screen.queryByRole("button", { name: "Remove Barracks" })).toBeNull()
    fireEvent.change(dialog.getByLabelText("Outward travel (s)"), { target: { value: "0" } })
    fireEvent.change(dialog.getByLabelText("Return travel (s)"), { target: { value: "7" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add order" }))
    const custom = view.container.querySelector(".order-custom-construction")!
    expect(custom.getAttribute("title")).toContain("Outward: 0s (override)")
    fireEvent.click(card)
    expect(view.container.querySelectorAll(".order-custom-construction")).toHaveLength(1)
    fireEvent.click(custom)
    dialog = within(screen.getByRole("dialog", { name: "Edit Barracks Construction" }))
    expect(dialog.getAllByText("Custom")).toHaveLength(2)
    fireEvent.click(dialog.getByRole("button", { name: "Use global (3.0 s) for outward travel" }))
    fireEvent.click(dialog.getByRole("button", { name: "Save order" }))
    fireEvent.click(view.container.querySelector(".event.building")!)
    fireEvent.click(screen.getByRole("menuitem", { name: "Edit" }))
    dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Outward travel (s)") as HTMLInputElement).value).toBe("3")
    expect((dialog.getByLabelText("Return travel (s)") as HTMLInputElement).value).toBe("7")
    fireEvent.keyDown(screen.getByRole("dialog"), { key: "Escape" })
    fireEvent.click(view.container.querySelector(".order-drag-handle")!)
    expect(screen.queryByRole("dialog")).toBeNull()
    view.unmount()
    render(<App />)
    expect(document.querySelectorAll(".order-custom-construction")).toHaveLength(1)
})

test.each([["Light", "Castle"], ["Dark", "Citadel"]])("%s upgrades use shared add and edit settings", (faction, building) => {
    const view = render(<App />)
    fireEvent.click(screen.getByRole("button", { name: faction, exact: true }))
    fireEvent.change(screen.getByLabelText("Starting gold"), { target: { value: "10000" } })
    fireEvent.change(screen.getByLabelText("Starting wood"), { target: { value: "10000" } })
    fireEvent.contextMenu(screen.getByRole("button", { name: new RegExp(`^${building} \\d`) }))
    const construction = within(screen.getByRole("dialog", { name: `Configure ${building} Construction` }))
    expect(construction.queryByRole("combobox", { name: "Construction time modifier" })).toBeNull()
    expect(construction.getByLabelText("Preparation (s)")).toHaveFocus()
    fireEvent.click(construction.getByRole("button", { name: "Cancel" }))
    const card = screen.getByRole("button", { name: `${building} upgrade` })
    const level = `${building} lvl 2`
    const configure = () => {
        fireEvent.click(card)
        fireEvent.contextMenu(screen.getByRole("menuitem", { name: new RegExp(level) }))
        return within(screen.getByRole("dialog", { name: `Configure ${building} Upgrade` }))
    }
    let dialog = configure()
    expect(dialog.queryByRole("combobox", { name: "Construction time modifier" })).toBeNull()
    expect(dialog.getByLabelText("Preparation (s)")).toHaveFocus()
    fireEvent.click(dialog.getByRole("button", { name: "Cancel" }))
    expect(view.container.querySelectorAll(".sortable-order li")).toHaveLength(0)
    dialog = configure()
    fireEvent.change(dialog.getByLabelText("Outward travel (s)"), { target: { value: "4" } })
    fireEvent.change(dialog.getByLabelText("Outward travel (s)"), { target: { value: "3" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add order" }))
    expect(view.container.querySelectorAll(".order-custom-construction")).toHaveLength(1)
    const row = screen.getByRole("button", { name: `Remove ${level}` }).closest("li")!
    const event = screen.getByRole("button", { name: level, exact: true })
    expect(row.title).toBe(event.title)
    expect(row.title).toContain("Outward: 3s (override)")
    expect(row.title).not.toMatch(/eligible for construction/i)

    fireEvent.click(screen.getByRole("button", { name: "Advanced" }))
    const global = screen.getByLabelText("Construction start delay (seconds)")
    fireEvent.change(global, { target: { value: "2.525" } })
    fireEvent.click(event)
    fireEvent.click(screen.getByRole("menuitem", { name: "Edit" }))
    dialog = within(screen.getByRole("dialog", { name: `Edit ${building} Upgrade` }))
    expect(dialog.getByLabelText("Preparation (s)")).toHaveFocus()
    expect((dialog.getByLabelText("Outward travel (s)") as HTMLInputElement).value).toBe("3")
    expect(dialog.getByText("Global: 2.525 s")).toBeTruthy()
    fireEvent.click(dialog.getByRole("button", { name: "Cancel" }))
    fireEvent.click(row)
    dialog = within(screen.getByRole("dialog", { name: `Edit ${building} Upgrade` }))
    fireEvent.click(dialog.getByRole("button", { name: "Use global (2.525 s) for outward travel" }))
    fireEvent.click(dialog.getByRole("button", { name: "Save order" }))
    expect(row.title).toBe(event.title)
    expect(row.title).toMatch(/^Command [^·]+ · Start [^·]+ · Finish [^·]+$/)

    fireEvent.change(global, { target: { value: "2" } })
    fireEvent.click(row)
    dialog = within(screen.getByRole("dialog", { name: `Edit ${building} Upgrade` }))
    expect((dialog.getByLabelText("Outward travel (s)") as HTMLInputElement).value).toBe("2")
})

