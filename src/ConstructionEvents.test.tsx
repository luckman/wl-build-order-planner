import { fireEvent, render, screen, within } from "@testing-library/react"
import App from "./App"

beforeEach(() => window.localStorage.clear())
afterEach(() => window.localStorage.clear())

test.each(["Light", "Dark"])("%s construction pre-add, row and timeline share settings without mutating other occurrences", faction => {
    const view = render(<App />)
    fireEvent.click(screen.getByRole("button", { name: faction, exact: true }))
    const card = screen.getByRole("button", { name: /^Barracks \d/ })
    fireEvent.contextMenu(card)
    let dialog = within(screen.getByRole("dialog"))
    expect(screen.queryByRole("button", { name: "Remove Barracks" })).toBeNull()
    fireEvent.change(dialog.getByLabelText("Outward travel (seconds)"), { target: { value: "0" } })
    fireEvent.change(dialog.getByLabelText("Return travel (seconds)"), { target: { value: "7" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add order" }))
    const custom = view.container.querySelector(".order-custom-construction")!
    expect(custom.getAttribute("title")).toContain("Outward: 0s (override)")
    fireEvent.click(card)
    expect(view.container.querySelectorAll(".order-custom-construction")).toHaveLength(1)
    fireEvent.click(custom)
    dialog = within(screen.getByRole("dialog"))
    fireEvent.click(dialog.getByRole("button", { name: "Use global outward travel (seconds)" }))
    fireEvent.click(dialog.getByRole("button", { name: "Save order" }))
    fireEvent.click(view.container.querySelector(".event.building")!)
    fireEvent.click(screen.getByRole("menuitem", { name: "Edit" }))
    dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Outward travel (seconds)") as HTMLInputElement).value).toBe("3")
    expect((dialog.getByLabelText("Return travel (seconds)") as HTMLInputElement).value).toBe("7")
    fireEvent.keyDown(screen.getByRole("dialog"), { key: "Escape" })
    fireEvent.click(view.container.querySelector(".order-drag-handle")!)
    expect(screen.queryByRole("dialog")).toBeNull()
    view.unmount()
    render(<App />)
    expect(document.querySelectorAll(".order-custom-construction")).toHaveLength(1)
})

test("right-click upgrade level configures only that requested upgrade; cancel leaves dependencies untouched", () => {
    const view = render(<App />)
    fireEvent.click(screen.getByRole("button", { name: "Castle upgrade" }))
    fireEvent.contextMenu(screen.getByRole("menuitem", { name: /Castle lvl 2/ }))
    let dialog = within(screen.getByRole("dialog"))
    fireEvent.click(dialog.getByRole("button", { name: "Cancel" }))
    expect(view.container.querySelectorAll(".sortable-order li")).toHaveLength(0)
    fireEvent.click(screen.getByRole("button", { name: "Castle upgrade" }))
    fireEvent.contextMenu(screen.getByRole("menuitem", { name: /Castle lvl 2/ }))
    dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Outward travel (seconds)"), { target: { value: "4" } })
    fireEvent.change(dialog.getByLabelText("Outward travel (seconds)"), { target: { value: "3" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add order" }))
    expect(view.container.querySelectorAll(".order-custom-construction")).toHaveLength(1)
    expect(view.container.querySelector(".order-custom-construction")?.textContent).toContain("Castle lvl 2")
})

test("idle-builder mode disables return controls without losing its override through drafts", () => {
    const view = render(<App />)
    fireEvent.contextMenu(screen.getByRole("button", { name: /^Barracks \d/ }))
    let dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Return travel (seconds)"), { target: { value: "9" } })
    fireEvent.click(dialog.getByLabelText("Use idle worker"))
    expect((dialog.getByLabelText("Return travel (seconds)") as HTMLInputElement).disabled).toBe(true)
    fireEvent.click(dialog.getByRole("button", { name: "Add order" }))
    expect(view.container.querySelector(".order-custom-construction")?.textContent).toContain("No available idle worker")
    view.unmount()
    const restored = render(<App />)
    fireEvent.click(restored.container.querySelector(".order-custom-construction")!)
    dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Use idle worker") as HTMLInputElement).checked).toBe(true)
    fireEvent.click(dialog.getByLabelText("Use idle worker"))
    expect((dialog.getByLabelText("Return travel (seconds)") as HTMLInputElement).value).toBe("9")
    expect((dialog.getByLabelText("Return travel (seconds)") as HTMLInputElement).disabled).toBe(false)
    fireEvent.click(dialog.getByRole("button", { name: "Save order" }))
})

test("preparation validates, persists and exposes computed departure through the shared editor", () => {
    const view = render(<App />)
    fireEvent.contextMenu(screen.getByRole("button", { name: /^Barracks \d/ }))
    let dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Preparation (seconds)"), { target: { value: "" } })
    expect((dialog.getByRole("button", { name: "Add order" }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(dialog.getByLabelText("Preparation (seconds)"), { target: { value: "10" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add order" }))
    const row = view.container.querySelector(".order-custom-construction")!
    expect(row.getAttribute("title")).toContain("Preparation: 10s")
    expect(row.getAttribute("title")).toContain("Departure ")
    view.unmount()
    const restored = render(<App />)
    fireEvent.click(restored.container.querySelector(".order-custom-construction")!)
    dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Preparation (seconds)") as HTMLInputElement).value).toBe("10")
    fireEvent.click(dialog.getByRole("button", { name: "Cancel" }))
})

test("construction renders distinct positive phases and omits zero travel and idle return", () => {
    const view = render(<App />)
    fireEvent.change(screen.getByLabelText("Starting gold"), { target: { value: "10000" } })
    fireEvent.change(screen.getByLabelText("Starting wood"), { target: { value: "10000" } })
    fireEvent.contextMenu(screen.getByRole("button", { name: /^Barracks \d/ }))
    let dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Preparation (seconds)"), { target: { value: "10" } })
    fireEvent.change(dialog.getByLabelText("Outward travel (seconds)"), { target: { value: "5" } })
    fireEvent.change(dialog.getByLabelText("Return travel (seconds)"), { target: { value: "7" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add order" }))
    const item = view.container.querySelector(".event.building")!
    expect(Array.from(item.querySelectorAll(".construction-phase")).map(phase => phase.getAttribute("aria-label"))).toEqual([
        "Preparation 0:00 to 0:10", "Outward travel 0:10 to 0:15", "Construction 0:15 to 0:45", "Return travel 0:45 to 0:52",
    ])
    fireEvent.click(view.container.querySelector(".sortable-order li")!)
    dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Preparation (seconds)"), { target: { value: "0" } })
    fireEvent.change(dialog.getByLabelText("Outward travel (seconds)"), { target: { value: "0" } })
    fireEvent.change(dialog.getByLabelText("Return travel (seconds)"), { target: { value: "0" } })
    fireEvent.click(dialog.getByRole("button", { name: "Save order" }))
    expect(item.querySelectorAll(".construction-phase")).toHaveLength(1)
})
