test("idle-builder mode disables return controls without losing its override through drafts", () => {
    const view = render(<App />)
    fireEvent.contextMenu(screen.getByRole("button", { name: /^Barracks \d/ }))
    let dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Return travel (s)"), { target: { value: "9" } })
    fireEvent.click(dialog.getByLabelText("Use idle worker"))
    expect((dialog.getByLabelText("Return travel (s)") as HTMLInputElement).disabled).toBe(true)
    expect((dialog.getByRole("button", { name: "Use global (3.0 s) for return travel" }) as HTMLButtonElement).disabled).toBe(true)
    expect(dialog.getByText("Idle builders skip return travel and remain idle")).toBeTruthy()
    fireEvent.click(dialog.getByRole("button", { name: "Add order" }))
    expect(view.container.querySelector(".order-custom-construction")?.textContent).toContain("No available idle worker")
    view.unmount()
    const restored = render(<App />)
    fireEvent.click(restored.container.querySelector(".order-custom-construction")!)
    dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Use idle worker") as HTMLInputElement).checked).toBe(true)
    fireEvent.click(dialog.getByLabelText("Use idle worker"))
    expect((dialog.getByLabelText("Return travel (s)") as HTMLInputElement).value).toBe("9")
    expect((dialog.getByLabelText("Return travel (s)") as HTMLInputElement).disabled).toBe(false)
    fireEvent.click(dialog.getByRole("button", { name: "Save order" }))
})

