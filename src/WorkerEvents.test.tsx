import { fireEvent, render, screen, within } from "@testing-library/react"
import App from "./App"

beforeEach(() => window.localStorage.clear())
afterEach(() => window.localStorage.clear())

test.each(["Light", "Dark"])("%s worker events add, edit, cancel and restore drafts", faction => {
    const view = render(<App />)
    fireEvent.click(screen.getByRole("button", { name: faction, exact: true }))
    fireEvent.click(screen.getByRole("button", { name: "Make idle", exact: true }))
    let dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Worker count") as HTMLInputElement).value).toBe("1")
    fireEvent.change(dialog.getByLabelText("Worker count"), { target: { value: "0" } })
    expect((dialog.getByRole("button", { name: "Add event" }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(dialog.getByLabelText("Worker count"), { target: { value: "1" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add event" }))
    expect(view.container.querySelector(".order")?.textContent).toContain("Idle 1")
    fireEvent.click(screen.getByRole("button", { name: /Change Make idle timestamp/ }))
    dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Worker count"), { target: { value: "2" } })
    fireEvent.click(dialog.getByRole("button", { name: "Cancel" }))
    fireEvent.click(screen.getByRole("button", { name: "Make active", exact: true }))
    dialog = within(screen.getByRole("dialog"))
    fireEvent.change(dialog.getByLabelText("Reactivation travel (seconds)"), { target: { value: "7" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add event" }))
    view.unmount()
    render(<App />)
    fireEvent.click(screen.getByRole("button", { name: /Change Make active timestamp/ }))
    dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Reactivation travel (seconds)") as HTMLInputElement).value).toBe("7")
    fireEvent.change(dialog.getByLabelText("Reactivation travel (seconds)"), { target: { value: "0" } })
    fireEvent.click(dialog.getByRole("button", { name: "Save event" }))
    fireEvent.click(screen.getByRole("button", { name: "Remove Make active" }))
    expect(screen.queryByRole("button", { name: "Remove Make active" })).toBeNull()
})

test.each(["Light", "Dark"])("%s idle casualty selection follows event time and survives upstream invalidation", faction => {
    render(<App />)
    fireEvent.click(screen.getByRole("button", { name: faction, exact: true }))
    fireEvent.click(screen.getByRole("button", { name: "Unit is killed", exact: true }))
    let dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Worker group") as HTMLSelectElement).value).toBe("gathering")
    expect((dialog.getByRole("option", { name: "Idle worker" }) as HTMLOptionElement).disabled).toBe(true)
    fireEvent.click(dialog.getByRole("button", { name: "Cancel" }))
    fireEvent.click(screen.getByRole("button", { name: "Make idle", exact: true }))
    fireEvent.click(within(screen.getByRole("dialog")).getByRole("button", { name: "Add event" }))
    fireEvent.click(screen.getByRole("button", { name: "Unit is killed", exact: true }))
    dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByRole("option", { name: "Idle worker" }) as HTMLOptionElement).disabled).toBe(false)
    fireEvent.change(dialog.getByLabelText("Worker group"), { target: { value: "idle" } })
    fireEvent.click(dialog.getByRole("button", { name: "Add event" }))
    fireEvent.click(screen.getByRole("button", { name: "Remove Make idle" }))
    fireEvent.click(screen.getByRole("button", { name: /Change Unit is killed timestamp/ }))
    dialog = within(screen.getByRole("dialog"))
    expect((dialog.getByLabelText("Worker group") as HTMLSelectElement).value).toBe("idle")
    expect(dialog.getByRole("alert").textContent).toContain("no available idle")
    fireEvent.change(dialog.getByLabelText("Worker group"), { target: { value: "gathering" } })
    fireEvent.click(dialog.getByRole("button", { name: "Save event" }))
    expect(screen.queryByRole("dialog")).toBeNull()
})
